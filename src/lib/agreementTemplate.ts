const fmt = (n: number, currency: string) =>
  new Intl.NumberFormat('en-GB', { style: 'currency', currency, maximumFractionDigits: 0 }).format(n || 0);

export const renderAgreement = (template: string, ctx: AgreementContext): string => {
  const totals = calcTotals(ctx);
  const balancePct = Math.max(0, 100 - Number(ctx.deposit_pct || 0));
  const map: Record<string, string> = {
    client_name: ctx.client_name || '',
    project_name: ctx.project_name || '',
    service_provider_name: ctx.service_provider_name || 'FastMedia.Pro',
    service_provider_address: ctx.service_provider_address || '',
    date: ctx.date || new Date().toLocaleDateString('en-GB'),
    dev_fee: fmt(ctx.dev_fee, ctx.currency),
    hosting_fee_yearly: fmt(ctx.hosting_fee_yearly, ctx.currency),
    deposit_pct: String(ctx.deposit_pct || 0),
    balance_pct: String(balancePct),
    deposit_amount: fmt(totals.depositAmount, ctx.currency),
    balance_due: fmt(totals.balanceDue, ctx.currency),
    late_penalty_pct_per_day: String(ctx.late_penalty_pct_per_day || 0),
    ai_token_ratio: String(ctx.ai_token_ratio || 3),
    ai_cost_100: fmt(totals.aiCost100, ctx.currency),
  };
  return template.replace(/\{\{\s*([a-z_]+)\s*\}\}/gi, (_, key) => map[key] ?? `{{${key}}}`);
};
